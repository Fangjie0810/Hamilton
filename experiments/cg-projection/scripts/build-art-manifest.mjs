import { readFile, writeFile, mkdir, readdir, copyFile } from 'node:fs/promises';
import path from 'node:path';

const root=process.cwd();
const read=async(file)=>{try{return JSON.parse(await readFile(file,'utf8'))}catch(error){if(error.code==='ENOENT')return [];throw error}};
const normalize=async(entries)=>{
  const result=[];
  for(const entry of entries){
    const disk=path.join(root,'public',entry.path);
    let buffer;try{buffer=await readFile(disk)}catch(error){if(error.code==='ENOENT')continue;throw error}
    const image={...entry};
    delete image.file;delete image.sourceFile;delete image.prompt;delete image.references;
    if(buffer.subarray(1,4).toString()==='PNG'){
      image.width=buffer.readUInt32BE(16);image.height=buffer.readUInt32BE(20);image.format='png';
      image.alphaChannel=[4,6].includes(buffer[25]);
    }
    if(image.alpha===undefined&&image.alphaChannel===false)image.alpha=false;
    result.push(image);
  }
  return result;
};
const portraitPlans=[...await read('art-direction/portraits-a.json'),...await read('art-direction/portraits-b.json')];
const usablePortraits=portraitPlans.filter(entry=>!entry.status||['generated','complete','ready','approved'].includes(entry.status));
const manifest={version:1,portraits:await normalize(usablePortraits),portraitDrafts:[],backgrounds:await normalize(await read('art-direction/backgrounds.json')),sprites:await normalize(await read('art-direction/sprites.json')),references:[]};
await mkdir('public/art/drafts',{recursive:true});
let rejected=[];try{rejected=await readdir('art-direction/rejected')}catch(error){if(error.code!=='ENOENT')throw error}
for(const file of rejected){
  const match=file.match(/^([a-z]+)-([abc])-checkerboard\.png$/);if(!match)continue;
  const [,character,variant]=match;const id=`${character}-${variant}`;
  if(manifest.portraits.some(item=>item.id===id))continue;
  await copyFile(path.join('art-direction/rejected',file),path.join('public/art/drafts',file));
  const plan=portraitPlans.find(item=>item.id===id);
  manifest.portraitDrafts.push({id,character,variant,style:plan?.style??{a:'电影动画式写实',b:'细腻绘画动画',c:'轮廓与色面写实'}[variant],path:`/art/drafts/${file}`,status:'draft',description:'草稿：人物已生成，但棋盘格已合并到底图，尚待背景修正。',alpha:false,format:'png'});
}
const referenceFiles={
  'a-ensemble.jpg':['Hamilton 与原卡群像','制服的蓝色长外套、浅黄翻领、奶油色背心与束发。'],
  'b-friends-disney.jpeg':['Laurens、Hamilton、Lafayette、Mulligan','比较束发轮廓、长衣摆、领巾，以及 Mulligan 的针织帽与深绿色外套。'],
  'a-burr.jpg':['Burr · Leslie Odom Jr.','参考面部形体、短发与克制的神态。'],
  'a-washington.jpg':['Washington · Christopher Jackson','参考宽肩、头型与人物姿态；军服另参考原版造型。'],
  'b-lafayette-officer-disney.jpeg':['Lafayette 的军官衣装','参考蓝色军服、浅黄镶边、肩饰与高束发。'],
};
await mkdir('public/art/references',{recursive:true});
for(const [file,[title,description]] of Object.entries(referenceFiles)){
 try{await copyFile(path.join('art-direction/references',file),path.join('public/art/references',file));manifest.references.push({title,description,path:`/art/references/${file}`,source:'https://press.disney.co.uk/gallery/hamilton-images',sourceLabel:'Disney 官方原版剧照 ↗'})}catch(error){if(error.code!=='ENOENT')throw error}
}
await mkdir('public/art',{recursive:true});
await writeFile('public/art/manifest.json',JSON.stringify(manifest,null,2));
await writeFile('src/data/artInventory.ts',`// Generated by scripts/build-art-manifest.mjs. Only approved, existing image files.\nexport const availableBackgrounds = new Set(${JSON.stringify(manifest.backgrounds.map(item=>item.id))});\nexport const availablePortraits = new Set(${JSON.stringify(manifest.portraits.map(item=>item.id))});\n`);
const counts=Object.fromEntries(['portraits','portraitDrafts','backgrounds','sprites','references'].map(key=>[key,manifest[key].length]));
console.log(JSON.stringify(counts));
if(process.argv.includes('--complete')){
 if(counts.portraits!==33||counts.backgrounds!==18||counts.sprites!==33)throw new Error('Asset collection incomplete');
 for(const type of ['portraits','backgrounds','sprites']){
   const ids=manifest[type].map(entry=>entry.id);if(new Set(ids).size!==ids.length)throw new Error(`Duplicate IDs: ${type}`);
 }
 console.log('PASS asset counts, unique IDs and all local file paths');
}
